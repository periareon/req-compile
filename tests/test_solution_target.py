"""Solutions compiled for one target must not be recycled for another."""

# pylint: disable=redefined-outer-name
from io import StringIO
from pathlib import Path

import pytest
from packaging.requirements import Requirement

import req_compile.compile
import req_compile.target
from req_compile.cmdline import build_repo, load_solutions, write_requirements_file
from req_compile.containers import DistInfo
from req_compile.repos import RepositoryInitializationError
from req_compile.repos.multi import MultiRepository
from req_compile.repos.solution import SolutionRepository
from req_compile.target import TargetEnvironment

from .conftest import MockRepository

LINUX = TargetEnvironment.from_spec("manylinux_2_28_x86_64", "3.11")
WINDOWS = TargetEnvironment.from_spec("win_amd64", "3.11")
WINDOWS_39 = TargetEnvironment.from_spec("win_amd64", "3.9")


def _write_solution(path: Path, header: str, body: str = "") -> Path:
    path.write_text(header + body, encoding="utf-8")
    return path


def _header(platform: str, python: str) -> str:
    return (
        "################################################################################\n"
        "## AUTOGENERATED: This file is autogenerated by req-compile.\n"
        "##\n"
        f"## Python: {python}\n"
        f"## Platform: {platform}\n"
        "##\n"
        "################################################################################\n"
        "\n"
    )


def test_header_is_read(tmp_path):
    solution = _write_solution(
        tmp_path / "solution.txt",
        _header("manylinux_2_28_x86_64", "3.11.14"),
        "six==1.16.0  # via requirements.in\n",
    )
    repo = SolutionRepository(solution, target=LINUX)
    assert repo.recorded_platform == "manylinux_2_28_x86_64"
    assert repo.recorded_python == "3.11.14"
    assert "six" in repo.solution


@pytest.mark.parametrize(
    "platform, python, target, expected",
    [
        # The same target, and the patch version does not matter.
        ("manylinux_2_28_x86_64", "3.11.14", LINUX, True),
        ("manylinux_2_28_x86_64", "3.11.0", LINUX, True),
        # Another platform or Python version.
        ("manylinux_2_28_x86_64", "3.11.14", WINDOWS, False),
        ("win_amd64", "3.11.14", WINDOWS_39, False),
        ("win_amd64", "3.9.21", WINDOWS_39, True),
        # Solutions compiled before the platform was recorded as a tag.
        ("Linux", "3.11.7", LINUX, True),
        ("Linux", "3.11.7", WINDOWS, False),
        ("Windows", "3.11.7", WINDOWS, True),
        # Unknown platforms cannot be checked.
        ("plan9", "3.11.7", WINDOWS, True),
    ],
)
def test_matches_target(tmp_path, platform, python, target, expected):
    solution = _write_solution(tmp_path / "solution.txt", _header(platform, python))
    assert (
        SolutionRepository(solution, target=target).matches_target(target) == expected
    )


def test_no_header_matches(tmp_path):
    solution = _write_solution(
        tmp_path / "solution.txt", "", "six==1.16.0  # via requirements.in\n"
    )
    assert SolutionRepository(solution, target=WINDOWS).matches_target(WINDOWS)


def test_host_compiles_recycle_any_platform(tmp_path):
    """Without an explicit platform, a solution from another machine is still recycled."""
    host = req_compile.target.host()
    solution = _write_solution(
        tmp_path / "solution.txt",
        _header("win_amd64", host.python_version_str),
    )
    assert SolutionRepository(solution, target=host).matches_target(host)


def _compile(repo, target):
    results, roots = req_compile.compile.perform_compile(
        [DistInfo("requirements.in", None, [Requirement("app")], meta=True)],
        repo,
        target=target,
    )
    return results, roots


@pytest.mark.usefixtures("mock_metadata")
def test_retarget_recompiles_without_upgrade(tmp_path):
    """Changing the target reselects artifacts and reevaluates dependencies.

    The `app` of the scenario depends on `colorama` only on Windows and on `uvloop`
    everywhere else. A solution compiled for Linux therefore knows nothing about
    `colorama`, and recycling it for Windows would silently miss the dependency.
    """
    index = MockRepository(target=LINUX)
    index.load_scenario("cross-platform")
    results, roots = _compile(index, LINUX)

    buffer = StringIO()
    buffer.write(_header("manylinux_2_28_x86_64", "3.11.0"))
    write_requirements_file(results, roots, repo=index, hashes=True, write_to=buffer)
    solution = tmp_path / "solution.txt"
    solution.write_text(buffer.getvalue(), encoding="utf-8")

    linux_solution = SolutionRepository(solution, target=LINUX)
    assert {node.key for node in linux_solution.solution} == {"app", "uvloop"}

    # Recycling the Linux solution for Windows is exactly the bug: the solution
    # answers for `app` first and never consults the index for `colorama`.
    stale = MultiRepository(
        SolutionRepository(solution, target=WINDOWS), MockRepository(target=WINDOWS)
    )
    stale.repositories[1].load_scenario("cross-platform")
    results, roots = _compile(stale, WINDOWS)
    assert {node.key for node in results.visit_nodes(roots)} == {"app", "uvloop"}

    # `load_solutions` flags the solution as compiled for another target, and the
    # repository built without it resolves the Windows dependencies.
    loaded = load_solutions([str(solution)], [], WINDOWS)
    assert len(loaded) == 1
    assert not loaded[0].matches_target(WINDOWS)

    windows_index = MockRepository(target=WINDOWS)
    windows_index.load_scenario("cross-platform")
    results, roots = _compile(windows_index, WINDOWS)
    assert {node.key for node in results.visit_nodes(roots)} == {"app", "colorama"}


def test_build_repo_without_index_rejects_other_target(tmp_path):
    """With no index to resolve from, a solution for another target is an error."""
    solution = _write_solution(
        tmp_path / "solution.txt",
        _header("manylinux_2_28_x86_64", "3.11.14"),
        "six==1.16.0  # via requirements.in\n",
    )
    with pytest.raises(
        RepositoryInitializationError, match="compiled for manylinux_2_28_x86_64"
    ):
        build_repo(
            solutions=[str(solution)],
            upgrade_packages=[],
            sources=[],
            excluded_sources=[],
            find_links=[],
            index_urls=[],
            wheeldir=str(tmp_path),
            no_index=True,
            target=WINDOWS,
        )

    repo = build_repo(
        solutions=[str(solution)],
        upgrade_packages=[],
        sources=[],
        excluded_sources=[],
        find_links=[],
        index_urls=[],
        wheeldir=str(tmp_path),
        no_index=True,
        target=LINUX,
    )
    assert isinstance(repo, SolutionRepository)
