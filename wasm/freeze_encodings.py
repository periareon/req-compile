#!/usr/bin/env python3
"""Emit a C table of frozen modules for what CPython needs before `sys.path` works.

The interpreter imports `encodings` while initializing (for the filesystem and
standard stream codecs), before anything on `sys.meta_path` that the bootstrap
installs. CPython's WASI builds do not freeze it, so the module freezes it
itself: the frozen importer, always present, finds these in
`PyImport_FrozenModules`. The running interpreter must be the same minor version
as the one embedded, since the bytecode format is per version.

Usage: freeze_encodings.py LIBDIR OUT.c
"""

import marshal
import os
import sys

MODULES = [
    ("encodings", "encodings/__init__.py", True),
    ("encodings.aliases", "encodings/aliases.py", False),
    ("encodings.ascii", "encodings/ascii.py", False),
    ("encodings.latin_1", "encodings/latin_1.py", False),
    ("encodings.utf_8", "encodings/utf_8.py", False),
    ("encodings.utf_8_sig", "encodings/utf_8_sig.py", False),
]


def main() -> None:
    libdir, out = sys.argv[1], sys.argv[2]
    chunks = []
    table = []
    for index, (name, relpath, is_package) in enumerate(MODULES):
        with open(os.path.join(libdir, relpath), "rb") as handle:
            code = compile(
                handle.read(), "<frozen " + name + ">", "exec", dont_inherit=True
            )
        data = marshal.dumps(code)
        chunks.append(
            "static const unsigned char frozen_%d[] = {%s};\n"
            % (index, ",".join(str(byte) for byte in data))
        )
        table.append(
            '    {"%s", frozen_%d, %d, %s},\n'
            % (name, index, len(data), "1" if is_package else "0")
        )
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(
            "/* Generated by freeze_encodings.py for Python %d.%d. */\n"
            % sys.version_info[:2]
        )
        handle.write("#include <Python.h>\n\n")
        handle.writelines(chunks)
        handle.write("\nconst struct _frozen req_compile_frozen_modules[] = {\n")
        handle.writelines(table)
        handle.write("    {0, 0, 0, 0},\n};\n")
    print("froze %d modules for Python %d.%d" % (len(MODULES), *sys.version_info[:2]))


if __name__ == "__main__":
    main()
